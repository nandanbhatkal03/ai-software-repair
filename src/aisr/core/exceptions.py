class AisrError(Exception):
    """Base class for all framework errors."""

class RepositoryError(AisrError): ...
class BuildSystemError(AisrError): ...
class TestExecutionError(AisrError): ...
class CoverageError(AisrError): ...
class LocalizationError(AisrError): ...
class PatchError(AisrError): ...
class ModelBackendError(AisrError): ...
